#!/usr/bin/env python3
"""INTERPRET the RUIN OCCUPANT pass's species tables out of Server.exe.

    python tools/extract_ruin_species.py            # human-readable
    python tools/extract_ruin_species.py --cpp      # CwTownRuinTables.h

Phase 1 of the ruin pass (0x4f16bb-0x4f1bbd) spends ZERO draws and builds two locals -- a
flat `vector<int>` and a `vector<SpeciesGroup>` -- from a five-way jump table on
`desc[0x1c]`, with a `desc[0x20] % 3` sub-switch inside arm 4.  Docs/RE_town_ruin.md §4.

The interpretation is NOT repeated here: it is `gate_town_ruin.species_tables()`, which is
already asserted against the binary and cross-checked against the DUNGEON assembler's
containers (Docs/RE_dungeon_species.md) every run.  This file only formats it, so there is
exactly one interpreter and the gate that proves it is the gate that regenerates the header
(lessons 7c, 7i, 7l).

⚠ The region shares tails through 0x4f1b93/0x4f1b96 and hoists its immediates above the
branch, so a block-at-a-time scrape of the listing drops the last id of five arms and still
produces a plausible-looking table.  Do not hand-edit the output.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from gate_town_ruin import species_tables                      # noqa: E402

# The arms a port has to be able to select, in the order CwTownRuinTables.h lays them out.
# `desc[0x1c]` 0..4 are the jump table's own five cases; arm 4 additionally switches on
# `desc[0x20] % 3`, so it occupies three rows.  ">4" is the default arm, and it is the one
# byte-identical to the dungeon assembler's default species container.
ROWS = [("sub0", (0, None)), ("sub1", (1, None)), ("sub2", (2, None)),
        ("sub3", (3, None)),
        ("sub4_m0", (4, 0)), ("sub4_m1", (4, 1)), ("sub4_m2", (4, 2)),
        ("default", ("default", None))]


def rows():
    _, tab = species_tables()
    out = []
    for name, key in ROWS:
        flat, groups = tab[key]
        out.append((name, flat, groups))
    return out


def main():
    data = rows()
    if "--cpp" not in sys.argv:
        for name, flat, groups in data:
            print("%-9s flat=%-28s groups=%s"
                  % (name, " ".join("0x%02x" % v for v in flat),
                     " | ".join("(%s / %s)"
                                % (" ".join("0x%02x" % v for v in a) or "-",
                                   " ".join("0x%02x" % v for v in b) or "-")
                                for a, b in groups)))
        return

    maxflat = max(len(f) for _, f, _ in data)
    maxgrp = max(len(g) for _, _, g in data)
    maxlist = max(max(len(a), len(b)) for _, _, g in data for a, b in g)

    print("// GENERATED by tools/extract_ruin_species.py in cw_decomp -- DO NOT EDIT.")
    print("// It interprets 0x4f16bb-0x4f1bbd out of Server.exe (through")
    print("// gate_town_ruin.species_tables(), the interpreter that gate already proves);")
    print("// gate_town_ruin.py re-runs the generator every time and diffs the result")
    print("// against these literals, so a hand edit fails the gate rather than surviving")
    print("// (lesson 7c/7i).")
    print("//")
    print("// The RUIN OCCUPANT pass's species tables -- Docs/RE_town_ruin.md section 4.  Phase 1")
    print("// spends no draws: the arm is chosen by desc[0x1c] (>4 -> kTownRuinDefault) and,")
    print("// for arm 4 only, by desc[0x20] %% 3.  Both selectors are already derived by")
    print("// cw_featuregen, so the whole table is reachable from the seed.")
    print("//")
    print("// WARNING: Arm 0 pushes 0x60 into the FLAT list twice.  That is byte-checked at")
    print("// 0x4f1774 / 0x4f17d5 and it is not a transcription slip: it makes the pack's")
    print("// species pick a %% 4 and not a %% 3.")
    print("// WARNING: `list1` is dead in this stage -- nothing reads a group's second vector.")
    print("//   It is carried because it is what makes two of these arms byte-identical to")
    print("//   the dungeon assembler's containers (Docs/RE_dungeon_species.md), which is")
    print("//   the only live evidence any of this decode has (lesson 7q).")
    print("#pragma once")
    print("#include <cstdint>")
    print("")
    print("namespace vx::cw {")
    print("")
    print("struct RuinSpeciesGroup { int32_t n0, n1; int32_t list0[%d], list1[%d]; };"
          % (maxlist, maxlist))
    print("struct RuinSpeciesTable {")
    print("    int32_t nFlat;")
    print("    int32_t flat[%d];" % maxflat)
    print("    int32_t nGroups;")
    print("    RuinSpeciesGroup groups[%d];" % maxgrp)
    print("};")
    print("")
    print("// index: desc[0x1c] 0..3 -> 0..3; desc[0x1c] == 4 -> 4 + desc[0x20] %% 3;")
    print("//        desc[0x1c] > 4  -> kTownRuinDefaultArm.")
    print("constexpr int kTownRuinDefaultArm = 7;")
    print("constexpr RuinSpeciesTable kTownRuinSpecies[%d] = {" % len(data))
    for name, flat, groups in data:
        fl = list(flat) + [0] * (maxflat - len(flat))
        gs = []
        for a, b in groups:
            aa = list(a) + [0] * (maxlist - len(a))
            bb = list(b) + [0] * (maxlist - len(b))
            gs.append("{%d, %d, {%s}, {%s}}"
                      % (len(a), len(b), ", ".join(str(v) for v in aa),
                         ", ".join(str(v) for v in bb)))
        while len(gs) < maxgrp:
            gs.append("{0, 0, {%s}, {%s}}" % (", ".join(["0"] * maxlist),
                                              ", ".join(["0"] * maxlist)))
        print("    {%d, {%s}, %d, {%s}},   // %s"
              % (len(flat), ", ".join(str(v) for v in fl), len(groups),
                 ", ".join(gs), name))
    print("};")
    print("")
    print("}  // namespace vx::cw")


if __name__ == "__main__":
    main()
